class Animal:
    """
    Базовый класс для всех животных.

    Атрибуты:
        name (str): Имя животного.
        age (int): Возраст животного в годах.
    """

    def __init__(self, name: str, age: int) -> None:
        """
        Инициализирует объект животного.

        :param name: Имя животного.
        :param age: Возраст животного в годах.
        """
        self.name = name
        self.age = age

    def make_sound(self) -> str:
        """
        Возвращает звук, который издает животное.
        Этот метод предполагается для переопределения в дочерних классах.

        :return: Звук животного.
        """
        return "Какой-то звук"

    def __str__(self) -> str:
        """
        Возвращает строковое представление животного.

        :return: Строка с описанием животного.
        """
        return f"{self.__class__.__name__}: {self.name}, {self.age} лет"

    def __repr__(self) -> str:
        """
        Возвращает строковое представление объекта для разработчиков.

        :return: Строка с техническим представлением объекта.
        """
        return f"{self.__class__.__name__}('{self.name}', {self.age})"


class Dog(Animal):
    """
    Дочерний класс, представляющий собаку.

    Атрибуты:
        breed (str): Порода собаки.
    """

    def __init__(self, name: str, age: int, breed: str) -> None:
        """
        Инициализирует объект собаки.

        :param name: Имя собаки.
        :param age: Возраст собаки в годах.
        :param breed: Порода собаки.
        """
        super().__init__(name, age)
        self.breed = breed

    def make_sound(self) -> str:
        """
        Переопределение метода из базового класса.

        Собака издает лай, поэтому метод возвращает "Гав-гав".

        :return: Звук собаки.
        """
        return "Гав-гав"

    def __str__(self) -> str:
        """
        Переопределение метода для более подробного описания собаки.

        :return: Строка с описанием собаки.
        """
        return f"{self.__class__.__name__}: {self.name}, {self.age} лет, порода {self.breed}"


# Пример создания объектов
dog = Dog("Шарик", 5, "Лабрадор")
print(dog)
print(dog.make_sound())
print(repr(dog))
